    private void setEditable()
    {
        jTextField1.setEditable(isEditable);
        jTextField2.setEditable(isEditable);
        jTextField3.setEditable(isEditable);
        if(isEditable)
        {
            jLabel7.setBackground(Color.GRAY);
            jButton1.setEnabled(true);
            jButton1.setBackground(new Color(180, 240, 180));
        }
        else
        {
            jLabel7.setBackground(Color.BLACK);
            jButton1.setEnabled(false);
            jButton1.setBackground(Color.WHITE);
        }
    }
