    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String name=jTextField1.getText();
        String email=jTextField2.getText();
        String old_mail=reg.getEmail();
        String phone=jTextField3.getText();
        String gender=(jRadioButton1.isSelected())?"M":"F";
        if(!validation.nameValid(name))
        {
            JOptionPane.showMessageDialog(this, "Invalid Format of Name");
            return;
        }
        if(!validation.emailValid(email))
        {
            JOptionPane.showMessageDialog(this, "Invalid Email");
            return;
        }
        if(!validation.phoneValid(phone))
        {
            JOptionPane.showMessageDialog(this, "Invalid Phone Number");
            return;
        }
        boolean res=DbOperations.update(old_mail, email, name, phone, gender, reg.getPassword());
        if(res)
        {
            isEditable=false;
            setEditable();
            JOptionPane.showMessageDialog(this, "Profile Updated Successfully.");
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Some Error Occurred During Updating Profile", "Error", JOptionPane.ERROR_MESSAGE);
        }
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

