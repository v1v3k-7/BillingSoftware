    private void increaseIcon(java.awt.event.MouseEvent evt)
    {
        javax.swing.JLabel label=(javax.swing.JLabel) evt.getSource();
        ImageIcon largeIcon = (ImageIcon) label.getClientProperty(LARGE_ICON_KEY);
        if(largeIcon==null && label.getIcon() instanceof ImageIcon)
        {
            ImageIcon normalIcon=(ImageIcon) label.getIcon();
            Image normalImg=normalIcon.getImage();
            int largeWidth = (int) (normalIcon.getIconWidth() * 1.10);
            int largeHeight = (int) (normalIcon.getIconHeight() * 1.10);
            largeIcon=new ImageIcon(normalImg.getScaledInstance(largeWidth, largeHeight, Image.SCALE_SMOOTH));
            
            label.putClientProperty(LARGE_ICON_KEY, largeIcon);
            label.putClientProperty(NORMAL_ICON_KEY, normalIcon);
        }
        if(largeIcon!=null)
        {
            label.setIcon(largeIcon);
        }
    }
    private void setNormalIcon(java.awt.event.MouseEvent evt)
    {
        javax.swing.JLabel label=(javax.swing.JLabel) evt.getSource();
        ImageIcon normalIcon=(ImageIcon) label.getClientProperty(NORMAL_ICON_KEY);
        if(normalIcon!=null)
        {
            label.setIcon(normalIcon);
        }
    }
