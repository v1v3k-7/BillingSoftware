    /**
     * @param args the command line arguments
     */
    public void formEmp()
    {
        ResultSet rs=DbOperations.getAllEmp();
        try
        {
            if(rs!=null)
            {
                Object[] row;
                int sr=0;
                while(rs.next())
                {
                   sr++;
                   String name=rs.getString("name");
                   String email=rs.getString("email");
                   String phone=rs.getString("phone");
                   row=new Object[]{sr, name, email, phone};
                   model.addRow(row);
                }
        }
        }
        catch(Exception e)
        {
            System.err.println("View Employee Error: "+ e);
        }
    }
