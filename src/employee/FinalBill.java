    public FinalBill(RegModel reg, String name, String email, String phone, String gender, String payment_type, HashMap<String, ArrayList<String>> map, int admin_id) {
        initComponents();
        this.reg=reg;
        jLabel3.setText(name + " (" + email + ")");
        this.name=name;
        this.email=email;
        this.phone=phone;
        this.gender=gender;
        this.payment_type=payment_type;
        float total_bill=0.0f;
        StringBuilder sb=new StringBuilder();
        for(Map.Entry<String, ArrayList<String>> e: map.entrySet())
        {
            ArrayList<String> al=e.getValue();
            String itemId=e.getKey();
            int quan=Integer.parseInt(al.get(0));
            float price=Float.parseFloat(al.get(1));
            String item_name=al.get(2);
            total_bill+= price*quan;
            sb.append(itemId);
            sb.append("~");
            sb.append(item_name);
            sb.append("~");
            sb.append(price);
            sb.append("~");
            sb.append(quan);
            sb.append("#");
        }
        total_bill=(total_bill*100)/100.0f;
        this.total_bill=total_bill;
        jLabel5.setText("Rs "+total_bill);
        this.products=sb.toString();
    }

