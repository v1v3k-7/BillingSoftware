    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String itemId=jTextField1.getText();
        String name=nameLabel.getText();
        if(!itemId.equals(currentItem))
        {
            JOptionPane.showMessageDialog(this, "Item Id Tempered.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String quan=(String)jComboBox1.getSelectedItem();
        String price_str=String.valueOf(price);
        String total_quan=String.valueOf(quanMap.getOrDefault(itemId, 0));
        if(map.containsKey(itemId))
        {
            ArrayList<String> al=map.get(itemId);
            int old_quan=Integer.valueOf(al.get(0));
            String new_quan=String.valueOf(old_quan + Integer.parseInt(quan));
            al.set(0, new_quan);
        }
        else
        {
            map.put(itemId, new ArrayList<>(Arrays.asList(quan, price_str, name, total_quan)));
            int cart_val=Integer.parseInt(cartLabel.getText());
            cartLabel.setText(String.valueOf(cart_val+1));
        }
        clear();
    }//GEN-LAST:event_jButton1ActionPerformed

