    private void jTextField1KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTextField1KeyReleased
        String itemId=jTextField1.getText();
        ResultSet rs=DbOperations.getItem(itemId);
        try
        {
            if(rs!=null)
            {
                if(rs.next())
                {
                    String name=rs.getString("name");
                    String desc=rs.getString("description");
                    int quan=rs.getInt("quantity");
                    quanMap.put(itemId, quan);
                    if(map.containsKey(itemId))
                    {
                        ArrayList<String> al=map.get(itemId);
                        int old_quan=Integer.valueOf(al.get(0));
                        quan-=old_quan;
                
                    }
                    quan=(quan>10)?10:quan;
                    for(int i=2; i<=quan; i++) jComboBox1.addItem(String.valueOf(i));
                    this.price=Math.round(rs.getFloat("price")*100)/100.0f;
                    InputStream is=rs.getBinaryStream("img");
                    nameLabel.setText(name);
                    jTextArea1.setText(desc);
                    jTextArea1.setCaretPosition(0);
                    priceLabel.setText("Rs. " + price);
                    BufferedImage img=ImageIO.read(is);
                    imageLabel.setIcon(new ImageIcon(img.getScaledInstance(imageLabel.getWidth(), imageLabel.getHeight(), Image.SCALE_SMOOTH)));
                    if(quan<=0) 
                    {
                        enableOFS(true);
                        return;
                    }
                    else enableOFS(false);
                    currentItem=itemId;
                    jButton1.setEnabled(true);
                    jButton2.setEnabled(true);
                    jComboBox1.setEnabled(true);
                }
            }
        }
        catch(Exception e)
        {
            System.out.println("Fetch Item Info Error: " + e);
        }
        
    }//GEN-LAST:event_jTextField1KeyReleased

