    private void jTable2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable2MouseClicked
        int row=jTable2.getSelectedRow();
        if(row==-1) return;
        String name=(String)model.getValueAt(row, 2);
        int quan=Integer.parseInt((String)model.getValueAt(row, 3));
        String itemId=(String)model.getValueAt(row, 1);
        int total_quan=Integer.parseInt(map.get(itemId).get(3));
        total_quan=(total_quan>10)?10:total_quan;
        for(int i=1; i<=total_quan; i++) jComboBox1.addItem(String.valueOf(i));
        jComboBox1.setSelectedItem(String.valueOf(quan));
        jLabel5.setText(name);
    }//GEN-LAST:event_jTable2MouseClicked

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int row=jTable2.getSelectedRow();
        if(row==-1) return;
        String itemId=(String)model.getValueAt(row, 1);
        int quan=Integer.valueOf((String)jComboBox1.getSelectedItem());
        float price=Float.parseFloat(map.get((String)model.getValueAt(row, 1)).get(1));
        int old_quan=Integer.valueOf((String)model.getValueAt(row, 3));
        float old_price=(Float)model.getValueAt(row, 4);
        if(old_quan==quan)
        {
            JOptionPane.showMessageDialog(this, "Item Updated in cart.");
            return;
        }
        map.get(itemId).set(0, String.valueOf(quan));
        float new_price=price*quan ;
        float new_price2=total_amount-old_price+new_price;
        model.setValueAt(new_price, row, 4);
        model.setValueAt(quan, row, 3);
        update_total_Price(Math.round(new_price2*100.0f)/100.0f);
        JOptionPane.showMessageDialog(this, "Item Updated in cart.");
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int row=jTable2.getSelectedRow();
        if(row==-1) return;
        String itemId=(String)model.getValueAt(row, 1);
        map.remove(itemId);
        float old_price=(Float)model.getValueAt(row, 4);
        model.removeRow(row);
        clear();
        JOptionPane.showMessageDialog(this, "Item Deleted.");
        float new_price=total_amount-old_price;
        update_total_Price(Math.round(new_price*100.0f)/100.0f);
        System.out.println("New Map Size: "+map.size());
    }//GEN-LAST:event_jButton3ActionPerformed

    private void buildTable()
    {
        int srNo=0;
        Object[] row;
        float total=0.0f;
        for(Map.Entry<String, ArrayList<String>> e:map.entrySet())
        {
            srNo++;
            String itemId=e.getKey();
            ArrayList<String> data=e.getValue();
            float price=Float.parseFloat(data.get(0)) * Float.parseFloat(data.get(1));
            total+=price;
            row=new Object[]{srNo, itemId, data.get(2), data.get(0), price};
            model.addRow(row);
        }
        update_total_Price(Math.round(total*100.0f)/100.0f);
    }
    
    private void update_total_Price(float price)
    {
        this.total_amount=price;
        jLabel7.setText("Rs "+price);
    }
