    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String name=jTextField1.getText();
        if(!validation.nameValid(name))
        {
            JOptionPane.showMessageDialog(this, "Invalid Format of Name.", "Invalid Name", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String phone=jTextField2.getText();
        if(!validation.phoneValid(phone))
        {
            JOptionPane.showMessageDialog(this, "Invalid Phone Number", "Invalid Phone", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String email=jTextField3.getText();
        if(!validation.emailValid(email))
        {
            JOptionPane.showMessageDialog(this, "Invalid Phone Number", "Invalid Phone", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String gender;
        if(jRadioButton1.isSelected()) gender="M";
        else if(jRadioButton2.isSelected()) gender="F";
        else 
        {
            JOptionPane.showMessageDialog(this, "Please Select the gender", "Blank Field", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String payment=(String)jComboBox1.getSelectedItem();
        if(!payment.equals("Cash"))
        {
            JOptionPane.showMessageDialog(this, "Currently we only accept cash.");
        }
        else
        {
            new FinalBill(reg, name, email, phone, gender, payment, map, reg.getId()).setVisible(true);
            setVisible(false);
        }
    }//GEN-LAST:event_jButton1ActionPerformed
    
    
    private void buildTable()
    {
        int srNo=0;
        Object[] row;
        float total=0.0f;
        for(Map.Entry<String, ArrayList<String>> e: map.entrySet())
        {
            srNo++;
            String itemId=e.getKey();
            ArrayList<String> al=e.getValue();
            String quan=al.get(0);
            String price=al.get(1);
            String name=al.get(2);
            float price_=Float.parseFloat(quan)*Float.parseFloat(price);
            price_=(price_*100)/100.0f;
            total+=price_;
            row=new Object[]{srNo, name, quan, price_};
            model.addRow(row);
        }
        jLabel4.setText("Rs "+total);
    }
