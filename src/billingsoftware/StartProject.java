    Timer timer=new Timer(delay, new ActionListener() {
        @Override
        public void actionPerformed(ActionEvent ae) {
            i++;
            jProgressBar1.setValue(i);
            if(i==30) jLabel4.setText("Loading Modules...");
            else if(i==60) jLabel4.setText("Connecting Server...");
            else if(i==90) jLabel4.setText("Starting App...");
            if (i==100) 
            {
                timer.stop();
                new Login().setVisible(true);
                setVisible(false);
            }
        }
    });
    public StartProject() {
        initComponents();
        timer.start();
    }

