    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String mail=jTextField1.getText();
        String pass=new String(jPasswordField1.getPassword());
        if(mail.equals("") || pass.equals(""))
        {
           JOptionPane.showMessageDialog(this, "Please enter your  Mail and Password", "Invalid Credentials", JOptionPane.ERROR_MESSAGE);
           return;
        }
        try
        {
            ResultSet rs=DbOperations.login(mail, pass);
            if(rs!=null)
            {
                if(rs.next())
                {
                    String name=rs.getString("name");
                    String email=rs.getString("email");
                    String password=rs.getString("password");
                    String gender=rs.getString("gender");
                    String module=rs.getString("module");
                    int id=rs.getInt("id");
                    String phone=rs.getString("phone");
                    RegModel rm=new RegModel();
                    rm.setEmail(email);
                    rm.setGender(gender);
                    rm.setId(id);
                    rm.setModule(module);
                    rm.setName(name);
                    rm.setPassword(password);
                    rm.setPhone(phone);
                    if(module.equals("admin"))
                    {
                        new AdminPanel(mail).setVisible(true);
                        setVisible(false);
                    }
                    else if(module.equals("emp"))
                    {
                        new EmpHome(rm).setVisible(true);
                        setVisible(false);
                    }
                    else if(module.equals("cust"))
                    {
                        new CustHome(rm).setVisible(true);
                        setVisible(false);
                    }
                }
                else
                {
                    JOptionPane.showMessageDialog(rootPane, "Invalid Email and Passowrd", "INVALID CREDS", JOptionPane.ERROR_MESSAGE);
                }
            }
            else
            {
                JOptionPane.showMessageDialog(rootPane, "No Account Found.", "ERROR", JOptionPane.ERROR_MESSAGE);
            }
        }
        catch(Exception e)
        {
            System.out.println("Login Error: " + e);
            JOptionPane.showMessageDialog(rootPane, "Login Failed due to some error", "ERROR", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

