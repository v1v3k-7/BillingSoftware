    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int row=jTable1.getSelectedRow();
        if(row==-1) return;
        String item_id=(String)model.getValueAt(row, 0);
        try
        {
            ResultSet rs=DbOperations.getItem(item_id);
            if(rs!=null)
            {
                if(rs.next())
                {
                    editable(true);
                    String name=rs.getString("name");
                    String price=rs.getString("price");
                    String desc=rs.getString("description");
                    String quan=rs.getString("quantity");
                    is=rs.getBinaryStream("img");
                    BufferedImage img=null;
                    try
                    {
                        img=ImageIO.read(is);
                        Image dimg = img.getScaledInstance(jLabel6.getWidth(), jLabel6.getHeight(), Image.SCALE_SMOOTH);
                        jLabel6.setIcon(new ImageIcon(dimg));
                    }
                    catch(Exception e)
                    {
                        jLabel6.setIcon(null);
                        System.out.println("Image Process Error in edit Item: " + e);
                    }
                    jTextField1.setText(name);
                    jTextField2.setText(price);
                    jTextField3.setText(quan);
                    jTextArea1.setText(desc);
                }
            }
        }
        catch(Exception e)
        {
            System.out.println("Error in Fetching Item Info: " + e);
        }
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int row=jTable1.getSelectedRow();
        if(row==-1)
        {
            JOptionPane.showMessageDialog(this, "Please Select an Item First");
            return;
        }
        int confirm=JOptionPane.showConfirmDialog(this, "Are you sure, You want to update this item?", "Delete Employee", JOptionPane.YES_NO_OPTION);
        if(confirm!=JOptionPane.YES_OPTION) return;
        
        String item_id=(String)model.getValueAt(row, 0);
        String name=jTextField1.getText();
        if(name.equals(""))
        {
            JOptionPane.showMessageDialog(this, "Item Name can't be empty");
            return;
        }
        if(name.length()>100)
        {
            JOptionPane.showMessageDialog(this, "Item Name is too long");
            return;
        }
        String price=jTextField2.getText();
        if(!validation.isFloat(price))
        {
            JOptionPane.showMessageDialog(this, "Invalid Price");
            return;
        }
        String quan=jTextField3.getText();
        if(!validation.isInt(quan))
        {
            JOptionPane.showMessageDialog(this, "Invalid Quantity");
            return;
        }
        String desc=jTextArea1.getText();
        if(desc.length()>1000)
        {
            JOptionPane.showMessageDialog(this, "Description is too large. max 1000 char is possible");
            return;
        }
        boolean res=DbOperations.updateItem(item_id, is, name, desc, quan, price);
        if(res)
        {
            JOptionPane.showMessageDialog(this, "Item Updated Successfully");
            jTable1.setValueAt(name, row, 1);
            jTable1.setValueAt(quan, row, 2);
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Failed To Update Item due to some error", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
//        FileChooser filechooser=new FileChooser();
        JFileChooser filechooser=new JFileChooser();
        FileNameExtensionFilter imageFilter = new FileNameExtensionFilter(
            "Image Files (*.jpg, *.jpeg, *.png, *.gif, *.bmp)", 
            "jpg", "jpeg", "png", "gif", "bmp"
        );
        filechooser.setFileFilter(imageFilter);
        filechooser.setAcceptAllFileFilterUsed(false);
        int i=filechooser.showOpenDialog(this);
        if(i==JFileChooser.APPROVE_OPTION)
        {
            File file = filechooser.getSelectedFile();
//            String img_path=file.getAbsolutePath();
            BufferedImage img = null;
            try 
            {
                is=new FileInputStream(file);
                img = ImageIO.read(file);
            } 
            catch (IOException e) 
            {
                System.out.println("Image Processing Error: "+ e);
            }
            Image dimg = img.getScaledInstance(jLabel6.getWidth(), jLabel6.getHeight(), Image.SCALE_SMOOTH);
            jLabel6.setIcon(new ImageIcon(dimg));
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int row=jTable1.getSelectedRow();
        if(row==-1)
        {
            JOptionPane.showMessageDialog(this, "Please Select an Item First");
            return;
        }
        
        int confirm=JOptionPane.showConfirmDialog(this, "Are you sure, You want to delete this employee?", "Delete Employee", JOptionPane.YES_NO_OPTION);
        if(confirm!=JOptionPane.YES_OPTION) return;
        
        String item_id=(String) model.getValueAt(row, 0);
        boolean isDeleted=DbOperations.deleteItem(item_id);
        if(isDeleted)
        {
            JOptionPane.showMessageDialog(this, "Item Deleted Successfully");
            clear();
            model.removeRow(row);
            editable(false);
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Item not deleted", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

