    public void formTable()
    {
        try
        {
            ResultSet rs=DbOperations.getAllItems();
            if(rs!=null)
            {
                Object[] row;
                while(rs.next())
                {
                    String id=rs.getString("item_id");
                    String name=rs.getString("name");
                    String quan=rs.getString("quantity");
                    row=new Object[]{id, name, quan};
                    model.addRow(row);
                }
            }
        }
        catch(Exception e)
        {
            System.out.println("Form Table Error: " + e);
        }
    }
