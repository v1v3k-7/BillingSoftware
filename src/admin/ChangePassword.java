    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String old=jTextField1.getText();
        String new_p=jTextField2.getText();
        String new_p2=new String(jPasswordField1.getPassword());
        if(old.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Please Enter your Old password");
            return;
        }
        if(new_p.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Please Enter your New password");
            return;
        }
        if(!new_p.equals(new_p2))
        {
            JOptionPane.showMessageDialog(this, "New Password didn't match.");
            return;
        }
        boolean res=DbOperations.checkPass(adminMail, old);
        if(!res)
        {
            JOptionPane.showMessageDialog(this, "Incorrect Old Password", "Password Incorrect", JOptionPane.ERROR_MESSAGE);
            return;
        }
        res=DbOperations.setNewPass(adminMail, new_p);
        if(res)
        {
            JOptionPane.showMessageDialog(this, "Password Changed Successfully.");
            clear();
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Failed due to some error", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

