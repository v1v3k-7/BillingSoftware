    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String email=jTextField2.getText();
        String name=jTextField1.getText();
        String password=jTextField3.getText();
        String phone=jTextField4.getText();
        if(email.equals("") || name.equals("") || password.equals("") || (!jRadioButton1.isSelected() && !jRadioButton2.isSelected()))
        {
            JOptionPane.showMessageDialog(this, "Please Fill all the field", "INCORRECT FIELD", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String gender=(jRadioButton1.isSelected())?"M":"F";
        if(!validation.phoneValid(phone))
        {
            JOptionPane.showMessageDialog(this, "Please enter correct phone number", "INCORRECT PHONE", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if(password.length()>100)
        {
            String inv="Password";
            JOptionPane.showMessageDialog(this, inv+" should be less than 100 character", "INCORRECT "+inv.toUpperCase(), JOptionPane.ERROR_MESSAGE);
            return; 
        }
        if(!validation.nameValid(name))
        {
            JOptionPane.showMessageDialog(this, "Please enter name in correct format.", "INCORRECT NAME", JOptionPane.ERROR_MESSAGE);
            return; 
        }
        if(!validation.emailValid(email))
        {
            JOptionPane.showMessageDialog(this, "Please enter email in correct format.", "INCORRECT EMAIL", JOptionPane.ERROR_MESSAGE);
            return; 
        }
        boolean isRegistered=DbOperations.regEmployee(email, name, "emp", phone, gender, password);
        if(!isRegistered)
        {
            JOptionPane.showMessageDialog(rootPane, "Some error occurred during registration.", "INVALID FIELD", JOptionPane.ERROR_MESSAGE);
        }
        else
        {
            JOptionPane.showMessageDialog(rootPane, "Employee Registered Successfully", "SUCCESS", JOptionPane.INFORMATION_MESSAGE);
            clear();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

