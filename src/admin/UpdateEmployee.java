    public void formEmp()
    {
        ResultSet rs=DbOperations.getAllEmp();
        try
        {
            if(rs!=null)
            {
                Object[] row;
                int sr=0;
                while(rs.next())
                {
                   sr++;
                   String name=rs.getString("name");
                   String email=rs.getString("email");
                   row=new Object[]{sr, name, email};
                   model.addRow(row);
                }
        }
        }
        catch(Exception e)
        {
            System.err.println("Form Employee Error: "+ e);
        }
        
    }
    
