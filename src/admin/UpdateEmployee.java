    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int row=jTable1.getSelectedRow();
        if(row==-1)
        {
            JOptionPane.showMessageDialog(this, "Please Select an Employee First");
            return;
        }
        
        int confirm=JOptionPane.showConfirmDialog(this, "Are you sure, You want to update this employee?", "Update Employee", JOptionPane.YES_NO_OPTION);
        if(confirm!=JOptionPane.YES_OPTION) return;
        
        String old_mail=(String) model.getValueAt(row, 2);
        String new_mail=jTextField2.getText();
        if(!validation.emailValid(new_mail))
        {
            JOptionPane.showMessageDialog(this, "Please Enter Correct Email", "Invalid Email", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String name=jTextField1.getText();
        if(!validation.nameValid(name))
        {
            JOptionPane.showMessageDialog(this, "Name should be in correct format", "Invalid Name", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String phone=jTextField3.getText();
        if(!validation.phoneValid(phone))
        {
            JOptionPane.showMessageDialog(this, "Please Enter Correct Phone Number", "Invalid Phone", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String gender=(jRadioButton1.isSelected())?"M":"F";
        String password=jTextField4.getText();
        if(password.length()<4)
        {
            JOptionPane.showMessageDialog(this, "Password is too short", "Invalid Password", JOptionPane.ERROR_MESSAGE);
            return;
        }
        boolean res=DbOperations.update(old_mail, new_mail, name, phone, gender, password);
        if(res)
        {
            JOptionPane.showMessageDialog(this, "Employee Updated SuccessFully");
            jTable1.setValueAt(new_mail, row, 2);
            jTable1.setValueAt(name, row, 1);
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Error in Updating Employee");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int row=jTable1.getSelectedRow();
        if(row==-1)
        {
            return;
        }
        String mail=(String) model.getValueAt(row, 2);
        try
        {
            ResultSet rs=DbOperations.getInfo(mail);
            if(rs==null) return;
            if(rs.next())
            {
                editable(true);
                jTextField1.setText(rs.getString("name"));
                jTextField2.setText(rs.getString("email"));
                jTextField3.setText(rs.getString("phone"));
                String gender=rs.getString("gender");
                jTextField4.setText(rs.getString("password"));
                if(gender.equals("M"))
                {
                    jRadioButton1.setSelected(true);
                    jRadioButton2.setSelected(false);
                }
                else 
                {
                    jRadioButton1.setSelected(false);
                    jRadioButton2.setSelected(true);
                }
            }
        }
        catch (Exception e)
        {
            System.out.println("Error in fetching mail info: " + e);
            JOptionPane.showMessageDialog(this, "Some error occurred", "Error", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int row=jTable1.getSelectedRow();
        if(row==-1)
        {
            JOptionPane.showMessageDialog(this, "Please Select an Employee First");
            return;
        }
        
        int confirm=JOptionPane.showConfirmDialog(this, "Are you sure, You want to delete this employee?", "Delete Employee", JOptionPane.YES_NO_OPTION);
        if(confirm!=JOptionPane.YES_OPTION) return;
        
        String mail=(String) model.getValueAt(row, 2);
        boolean isDeleted=DbOperations.deleteEmp(mail);
        if(isDeleted)
        {
            JOptionPane.showMessageDialog(this, "Employee Deleted Successfully");
            clear();
            model.removeRow(row);
            editable(false);
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Employee not deleted", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

