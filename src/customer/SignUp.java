    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String name=jTextField1.getText();
        String email=jTextField2.getText();
        String pass=new String(jPasswordField1.getPassword());
        String pass2=new String(jPasswordField2.getPassword());
        String phone=jTextField3.getText();
        if(!validation.nameValid(name))
        {
            JOptionPane.showMessageDialog(this, "Invalid Format of Name");
            return;
        }
        else if(!validation.emailValid(email))
        {
            JOptionPane.showMessageDialog(this, "Invalid Email");
            return;
        }
        else if(!validation.phoneValid(phone))
        {
            JOptionPane.showMessageDialog(this, "Invalid Phone Number");
            return;
        }
        String gender;
        if(jRadioButton1.isSelected()) gender="M";
        else if(jRadioButton2.isSelected()) gender="F";
        else
        {
            JOptionPane.showMessageDialog(this, "Please Select Gender.");
            return;
        }
        if(pass.length()>100 || pass.length()<5)
        {
            JOptionPane.showMessageDialog(this, "Invalid Length of password.");
            return;
        }
        if(!pass.equals(pass2))
        {
            JOptionPane.showMessageDialog(this, "Password din't match", "Password Mismatch", JOptionPane.ERROR_MESSAGE);
            return;
        }
        boolean res=DbOperations.regEmployee(email, name, "cust", phone, gender, pass);
        if(!res)
        {
            JOptionPane.showMessageDialog(this, "Registration Failed due to some error", "Failed", JOptionPane.ERROR_MESSAGE);
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Registration SuccessFull");
            new Login().setVisible(true);
            setVisible(false);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

