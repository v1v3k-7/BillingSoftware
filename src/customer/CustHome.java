    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int row=jTable1.getSelectedRow();
        if(row==-1) return;
        int orderId=Integer.parseInt(((String)order_list_model.getValueAt(row, 1)).substring(2));
        try
        {
            ResultSet rs=DbOperations.get_order(orderId);
            if(rs!=null)
            {
                if(rs.next())
                {
                    item_list_model.setRowCount(0);
                    String[] items=rs.getString("products").split("#");
                    int srNo=0;
                    float total_price=0.0f;
                    for(String item: items)
                    {
                        srNo++;
                        String[] item_data=item.split("~");
                        String name=item_data[1];
                        float price=Float.parseFloat(item_data[2]);
                        int quan=Integer.parseInt(item_data[3]);
                        float total=(price*quan*100)/100.0f;
                        total_price+=total;
                        item_list_model.addRow(new Object[]{srNo, name, quan, total});
                    }
                    jLabel5.setVisible(true);
                    jScrollPane2.setVisible(true);
                }
            }
        }
        catch(Exception e)
        {
            System.err.println("Error in Fetching Order details from Order Id: "+e);
        }
    }//GEN-LAST:event_jTable1MouseClicked
    
    private void buildOrderTable()
    {
        try
        {
            ResultSet rs=DbOperations.get_orders(reg.getId());
            if(rs!=null)
            {
                int srNo=0;
                while(rs.next())
                {
                    srNo++;
                    int orderId=rs.getInt("order_id");
                    LocalDateTime ldt=rs.getTimestamp("datetime").toLocalDateTime();
                    DateTimeFormatter dtf=DateTimeFormatter.ofPattern("dd-MM-yyyy");
                    DateTimeFormatter dtf2=DateTimeFormatter.ofPattern("hh:mm a");
                    String date=ldt.format(dtf);
                    String time=ldt.format(dtf2);
                    float amount=rs.getFloat("price");
                    order_list_model.addRow(new Object[]{srNo, "BS"+orderId, date, time, amount});
                }
            }
        }
        catch(Exception e)
        {
            System.err.println("Unable to Fetch All Orders: "+e);
        }
    }
